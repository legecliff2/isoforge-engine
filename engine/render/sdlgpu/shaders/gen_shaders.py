#!/usr/bin/env python3
"""Regenerates src/sprite_shaders.inl from the GLSL/MSL sources in this folder.

Requires glslangValidator. Output is committed so normal builds need no shader toolchain.
(ARCHITECTURE.md §6 plans SDL_shadercross from HLSL at build time; see PR notes.)"""
import pathlib, subprocess, tempfile

here = pathlib.Path(__file__).resolve().parent
out = here.parent / "src" / "sprite_shaders.inl"

def spirv(src):
    with tempfile.TemporaryDirectory() as d:
        o = pathlib.Path(d) / "out.spv"
        subprocess.check_call(["glslangValidator", "-V", "--quiet", str(here / src), "-o", str(o)])
        return o.read_bytes()

def arr(name, data):
    body = ",".join(f"0x{b:02x}" for b in data)
    lines = [body[i:i + 120] for i in range(0, len(body), 120)]
    return f"static const unsigned char {name}[] = {{\n" + "\n".join(lines) + "\n};\n"

msl = (here / "sprite.metal").read_text()
txt = "// Generated by shaders/gen_shaders.py. Do not edit.\n"
txt += arr("kSpriteVertSpv", spirv("sprite.vert"))
txt += arr("kSpriteFragSpv", spirv("sprite.frag"))
txt += "static const char kSpriteMsl[] = R\"MSL(\n" + msl + ")MSL\";\n"
out.write_text(txt)
print("wrote", out)
